export function normalizeUiLang(value) {
  return SUPPORTED_UI_LANGS.includes(value) ? value : DEFAULT_UI_LANG;
}

export function getUiMessages(value) {
  return MESSAGES[normalizeUiLang(value)];
}

export function formatUiMessage(messages, key, variables = {}) {
  const template = messages?.[key] ?? MESSAGES.en[key] ?? key;
  return Object.entries(variables).reduce(
    (output, [name, value]) => output.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

export function getInspectorMessages(value) {
  const messages = getUiMessages(value);
  return Object.fromEntries(
    Object.entries(messages).filter(([key]) =>
      key.startsWith("inspector.") || key.startsWith("lens."),
    ),
  );
}
